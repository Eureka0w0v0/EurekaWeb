#!/usr/bin/env python3
"""Generate the photo theatre's cards in index.html from data/photos.json.

data/photos.json is the one place the photo list lives:

    {
      "insert": "353ada2ec7798bf29b0ea234c88fc0c3",
      "queue": ["01362e483ec3218bab9580a317f7f619", "IMG_5077", ...]
    }

`insert` is the card that drops into the stack as the section scrolls in;
`queue` is the stack, in order. Each entry is a basename that must exist as
a .webp in all three tiers: images/photo-preview, images/medium and
images/full (tools/add-photo.py makes all three).

The cards used to be written by hand, and each one carries ordering state --
data-photo-base and the number in its aria-label -- that the scroll
choreography in js/photo/ reads. Deriving both from the queue position means
they can no longer drift from the order of the cards.

The cards go between marker comments in index.html, one pair for the
dropping card and one inside .photo-queue; everything around them stays
hand-written. URLs are written with a placeholder stamp and
tools/stamp-assets.py is run afterwards to fill in the real ones.

    python3 tools/build-photos.py          # regenerate the cards, then restamp
    python3 tools/build-photos.py --check  # exit 1 if index.html is out of date

Standard library only.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "index.html"
PHOTOS = ROOT / "data" / "photos.json"
IMAGES = ROOT / "images"
TIERS = ("photo-preview", "medium", "full")
NAME = re.compile(r"^[A-Za-z0-9._-]+$")
STAMP = re.compile(r"\?v=[A-Za-z0-9._-]+")

# The dropping card and the front of the stack keep loading="eager", as the
# hand-written cards had them; every other card is lazy.
EAGER_QUEUE_CARDS = 2

INSERT_MARKERS = (
    "<!-- photo-insert:start -- generated by tools/build-photos.py from data/photos.json -->",
    "<!-- photo-insert:end -->",
)
QUEUE_MARKERS = (
    "<!-- photo-queue:start -- generated by tools/build-photos.py from data/photos.json -->",
    "<!-- photo-queue:end -->",
)


class PhotoError(Exception):
    """data/photos.json or index.html is not in a shape this can work with."""


def load_photos(path: Path = PHOTOS) -> dict:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as error:
        raise PhotoError(f"{path.relative_to(ROOT)} does not exist") from error
    except json.JSONDecodeError as error:
        raise PhotoError(f"{path.relative_to(ROOT)} is not valid JSON: {error}") from error

    if not isinstance(data, dict):
        raise PhotoError("data/photos.json must be an object")
    unknown = set(data) - {"_about", "insert", "queue"}
    if unknown:
        raise PhotoError(f"unknown key(s) in data/photos.json: {', '.join(sorted(unknown))}")
    insert, queue = data.get("insert"), data.get("queue")
    if not isinstance(insert, str):
        raise PhotoError('"insert" must be one photo name')
    if not isinstance(queue, list) or not queue or not all(isinstance(n, str) for n in queue):
        raise PhotoError('"queue" must be a non-empty list of photo names')

    names = [insert, *queue]
    problems = []
    for name in names:
        if not NAME.match(name):
            problems.append(f"{name!r}: only letters, digits, '.', '_' and '-' are allowed")
            continue
        for tier in TIERS:
            if not (IMAGES / tier / f"{name}.webp").is_file():
                problems.append(f"{name}: images/{tier}/{name}.webp is missing")
    duplicates = sorted({name for name in names if names.count(name) > 1})
    if duplicates:
        problems.append(f"listed more than once: {', '.join(duplicates)}")
    if problems:
        raise PhotoError("data/photos.json:\n  " + "\n  ".join(problems))
    return data


def urls(name: str) -> dict[str, str]:
    """The three tier URLs, with a placeholder stamp for stamp-assets.py."""
    return {tier: f"./images/{tier}/{name}.webp?v=0" for tier in TIERS}


def image_lines(name: str, loading: str, extra: tuple[str, ...] = ()) -> list[str]:
    u = urls(name)
    return [
        "<img",
        '  class="photo-card-image"',
        f'  src="{u["photo-preview"]}"',
        f'  data-preview-src="{u["photo-preview"]}"',
        f'  data-full-src="{u["full"]}"',
        f'  data-full-srcset="{u["medium"]} 1280w, {u["full"]} 1920w"',
        '  data-full-sizes="(max-width: 900px) 92vw, min(88vw, 1200px)"',
        '  alt=""',
        f'  loading="{loading}"',
        '  decoding="async"',
        '  draggable="false"',
        *(f"  {attribute}" for attribute in extra),
        "/>",
    ]


def insert_card(name: str) -> list[str]:
    return [
        '<article class="photo-card photo-floating-card" data-photo-insert="1" '
        'data-i18n-aria="photoInsertLabel" aria-label="即将插入的照片 1">',
        *(f"  {line}" for line in image_lines(name, "eager", ('fetchpriority="high"',))),
        '  <span class="photo-card-shine" aria-hidden="true"></span>',
        "</article>",
    ]


def queue_card(name: str, position: int) -> list[str]:
    loading = "eager" if position <= EAGER_QUEUE_CARDS else "lazy"
    return [
        f'<article class="photo-card photo-queue-card" data-photo-base="{position}" '
        f'data-i18n-aria="photoCardLabel" aria-label="照片 {position}">',
        *(f"  {line}" for line in image_lines(name, loading)),
        "</article>",
    ]


def replace_between(html: str, markers: tuple[str, str], lines: list[str]) -> str:
    start_marker, end_marker = markers
    pattern = re.compile(
        r"(?P<indent>[ \t]*)" + re.escape(start_marker) + r".*?" + re.escape(end_marker), re.DOTALL
    )
    found = pattern.findall(html)
    if len(found) != 1:
        raise PhotoError(f"index.html needs exactly one {start_marker!r} ... {end_marker!r} pair")
    indent = pattern.search(html).group("indent")
    block = "\n".join([start_marker, *lines, end_marker])
    block = "\n".join(f"{indent}{line}" if i else line for i, line in enumerate(block.split("\n")))
    return pattern.sub(lambda m: m.group("indent") + block, html, count=1)


def render(html: str, photos: dict) -> str:
    html = replace_between(html, INSERT_MARKERS, insert_card(photos["insert"]))
    queue = [line for position, name in enumerate(photos["queue"], 1) for line in queue_card(name, position)]
    return replace_between(html, QUEUE_MARKERS, queue)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="report whether index.html is current, change nothing")
    args = parser.parse_args()

    try:
        photos = load_photos()
        html = INDEX.read_text(encoding="utf-8")
        rendered = render(html, photos)
    except PhotoError as error:
        print(error, file=sys.stderr)
        return 2

    # Stamps are stamp-assets.py's business; compare everything else.
    if STAMP.sub("?v=", rendered) == STAMP.sub("?v=", html):
        print(f"photo cards match data/photos.json ({len(photos['queue'])} in the queue)")
        return 0

    if args.check:
        print("index.html's photo cards do not match data/photos.json", file=sys.stderr)
        print("\nrun: python3 tools/build-photos.py", file=sys.stderr)
        return 1

    INDEX.write_text(rendered, encoding="utf-8")
    print(f"index.html: regenerated {len(photos['queue'])} queue card(s) and the dropping card", flush=True)
    return subprocess.run([sys.executable, str(ROOT / "tools" / "stamp-assets.py")], check=False).returncode


if __name__ == "__main__":
    raise SystemExit(main())
